def flat(path: Path, size, bg, title: str, subtitle: str = "", frame=BRASS, title_y: float = 0.12):
    img = Image.new("RGB", size, bg)
    dr = ImageDraw.Draw(img, "RGBA")
    w, h = size
    for i in range(0, w + h, 48):  # ink hatching on the edges (style signature, very rough)
        dr.line([(i, 0), (i - h, h)], fill=INK + (40,), width=2)
    dr.rectangle([16, 16, w - 16, h - 16], outline=frame + (255,), width=6)
    draw_label(dr, (w / 2, h * title_y), title, max(22, h // 18))
    if subtitle:
        dr.multiline_text((w / 2, h * 0.88), subtitle, font=font(max(16, h // 34)), fill=IVORY, anchor="mm", align="center")
    dr.text((w - 30, h - 30), "ЗАГЛУШКА / PLACEHOLDER", font=font(max(12, h // 50)), fill=(255, 255, 255, 140), anchor="rs")
    return img, dr


def make_portrait(who: str, emotion: str, coat, skin=(0xE0, 0xC0, 0xA0), hair=INK):
    w, h = 800, 1000
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    dr = ImageDraw.Draw(img)
    dr.rounded_rectangle([110, 600, 690, 1000], radius=140, fill=coat + (255,), outline=INK + (255,), width=6)
    dr.rectangle([350, 520, 450, 640], fill=skin + (255,))
    dr.ellipse([250, 200, 550, 560], fill=skin + (255,), outline=INK + (255,), width=6)
    dr.chord([235, 170, 565, 450], 180, 360, fill=hair + (255,))
    eye_y = 380
    mouth = {"smile": (330, 460, 470, 500, 20, 160), "upset": (340, 470, 460, 520, 200, 340),
             "surprised": None, "guarded": (340, 470, 460, 480, 0, 180)}.get(emotion)
    for ex in (330, 470):
        dr.ellipse([ex - 18, eye_y - 12, ex + 18, eye_y + 12], fill=INK + (255,))
    if emotion == "surprised":
        dr.ellipse([375, 455, 425, 505], outline=INK + (255,), width=6)
    elif mouth:
        x0, y0, x1, y1, a0, a1 = mouth
        dr.arc([x0, y0, x1, y1], a0, a1, fill=INK + (255,), width=6)
    else:
        dr.line([(360, 480), (440, 480)], fill=INK + (255,), width=6)
    draw_label(dr, (w / 2, 80), who, 54)
    draw_label(dr, (w / 2, 140), emotion, 36, fill=LAMP)
    draw_label(dr, (w / 2, 960), "ЗАГЛУШКА", 30)
    return img


def make_item(path: Path, label: str, col, shape: str):
    img = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
    dr = ImageDraw.Draw(img)
    dr.rounded_rectangle([8, 8, 248, 248], radius=28, fill=IVORY + (255,), outline=BRASS + (255,), width=6)
    if shape == "owl":
        dr.ellipse([70, 60, 186, 210], fill=col + (255,), outline=INK + (255,), width=4)
        for ex in (105, 151):
            dr.ellipse([ex - 18, 90, ex + 18, 126], fill=IVORY + (255,), outline=INK + (255,), width=3)
            dr.ellipse([ex - 7, 101, ex + 7, 115], fill=INK + (255,))
    elif shape == "ticket":
        dr.rectangle([40, 80, 216, 176], fill=(0xE8, 0xD8, 0xB0, 255), outline=INK + (255,), width=4)
        dr.line([(160, 80), (160, 176)], fill=INK + (255,), width=2)
    elif shape == "glasses":
        dr.ellipse([40, 100, 116, 160], outline=INK + (255,), width=8)
        dr.ellipse([140, 100, 216, 160], outline=INK + (255,), width=8)
        dr.line([(116, 125), (140, 125)], fill=INK + (255,), width=6)
    elif shape == "key":
        dr.ellipse([40, 90, 110, 160], outline=col + (255,), width=12)
        dr.rectangle([110, 118, 220, 132], fill=col + (255,))
        dr.rectangle([190, 132, 202, 160], fill=col + (255,))
    dr.text((128, 230), label, font=font(20, True), fill=INK, anchor="mb")
    img.save(path)


def save(img: Image.Image, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)


