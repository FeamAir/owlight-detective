def yaw_to_x(yaw: float, w: int) -> float:
    return (0.5 + yaw / 360.0) * w


def pitch_to_y(pitch: float, h: int) -> float:
    return (0.5 - pitch / 180.0) * h


def wrap_draws(x0: float, x1: float, w: int):
    """Yield x-offsets so shapes crossing the seam are drawn on both sides."""
    for off in (-w, 0, w):
        if x1 + off >= 0 and x0 + off <= w:
            yield off


def draw_label(dr: ImageDraw.ImageDraw, xy, text: str, size: int, fill=IVORY, outline=INK, anchor="mm"):
    dr.text(xy, text, font=font(size, True), fill=fill, anchor=anchor, stroke_width=max(2, size // 10), stroke_fill=outline)


def make_pano(vp_id: str, vp: dict, hotspots: dict, w: int, h: int) -> Image.Image:
    sc = SCENES[vp_id]
    img = Image.new("RGB", (w, h))
    px = img.load()
    horizon = int(pitch_to_y(0, h))
    top = sc["sky"] if not sc["indoor"] else mix(sc["sky"], (0, 0, 0), 0.3)
    for y in range(h):
        if y < horizon:
            c = mix(mix(top, (0xB8, 0xC2, 0xC4) if not sc["indoor"] else sc["sky"], y / horizon), top, 0.0)
        else:
            c = mix(sc["ground"], mix(sc["ground"], (0, 0, 0), 0.5), (y - horizon) / (h - horizon))
        for x in range(0, w, 1):
            px[x, y] = c
    dr = ImageDraw.Draw(img, "RGBA")
    # silhouettes
    for label, y0, y1, p0, p1, col, shape in sc["items"]:
        if y1 < y0:
            y1 += 360
        x0, x1 = yaw_to_x(y0, w), yaw_to_x(y1, w)
        top_y, bot_y = pitch_to_y(p1, h), pitch_to_y(p0, h)
        for off in wrap_draws(x0, x1, w):
            box = [x0 + off, top_y, x1 + off, bot_y]
            if shape == "house":
                dr.rectangle(box, fill=col + (255,), outline=INK + (255,), width=4)
                roof_h = (bot_y - top_y) * 0.35
                dr.polygon([(box[0] - 10, box[1]), ((box[0] + box[2]) / 2, box[1] - roof_h), (box[2] + 10, box[1])],
                           fill=mix(col, INK, 0.4) + (255,), outline=INK + (255,))
            elif shape == "gate":
                for k in range(9):
                    xx = box[0] + (box[2] - box[0]) * k / 8
                    dr.line([(xx, box[1]), (xx, box[3])], fill=INK + (255,), width=5)
                dr.line([(box[0], box[1]), (box[2], box[1])], fill=INK + (255,), width=8)
            elif shape == "band":
                dr.rectangle(box, fill=col + (150,))
            elif shape == "road":
                cx = (box[0] + box[2]) / 2
                dr.polygon([(cx - (box[2] - box[0]) * 0.12, box[1]), (cx + (box[2] - box[0]) * 0.12, box[1]),
                            (box[2], box[3]), (box[0], box[3])], fill=col + (255,), outline=INK + (180,))
            elif shape == "fountain":
                dr.ellipse(box, fill=col + (255,), outline=INK + (255,), width=4)
                cx = (box[0] + box[2]) / 2
                dr.rectangle([cx - 12, box[1] - 70, cx + 12, box[1] + 20], fill=(0x9A, 0x96, 0x8C, 255), outline=INK + (255,))
                dr.ellipse([cx - 26, box[1] - 110, cx + 26, box[1] - 60], fill=(0x9A, 0x96, 0x8C, 255), outline=INK + (255,))
            else:
                dr.rectangle(box, fill=col + (255,), outline=INK + (255,), width=4)
            draw_label(dr, ((box[0] + box[2]) / 2, box[1] - 18), label, max(18, h // 75))
    # blank medallions where the game draws signs (overlays)
    for ov in vp.get("overlays", []) or []:
        cx, cy = yaw_to_x(ov["yaw"], w), pitch_to_y(ov["pitch"], h)
        r = ov["size_deg"] / 360.0 * w / 2
        dr.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(0x30, 0x30, 0x30, 255), outline=BRASS + (255,), width=4)
    # degree grid
    gfont = font(max(14, h // 90))
    for yaw in range(0, 360, 15):
        x = yaw_to_x(yaw if yaw <= 180 else yaw - 360, w)
        major = yaw % 30 == 0
        dr.line([(x, 0), (x, h)], fill=(255, 255, 255, 70 if major else 35), width=2 if major else 1)
        if major:
            for p in (60, 30, -30, -60):
                dr.text((x + 6, pitch_to_y(p, h) + 4), f"{yaw}°", font=gfont, fill=(255, 255, 255, 170))
    for p in range(-80, 90, 10):
        y = pitch_to_y(p, h)
        dr.line([(0, y), (w, y)], fill=(255, 255, 255, 90 if p == 0 else 30), width=3 if p == 0 else 1)
        if p % 20 == 0:
            for yaw in (-135, -45, 45, 135):
                dr.text((yaw_to_x(yaw, w) + 6, y + 2), f"pitch {p:+d}", font=gfont, fill=(255, 255, 255, 140))
    # sides
    for yaw, text in ((0, "0° ВПЕРЁД"), (90, "90° ВПРАВО"), (180, "180° НАЗАД"), (-90, "270° ВЛЕВО")):
        x = yaw_to_x(yaw, w)
        for off in ((0,) if yaw != 180 else (-w / 2 + 8, w / 2 - 8)):
            xx = x if yaw != 180 else (8 if off < 0 else w - 8)
            anchor = "mm" if yaw != 180 else ("lm" if off < 0 else "rm")
            draw_label(dr, (xx, pitch_to_y(-55, h)), text, max(28, h // 30), fill=LAMP, anchor=anchor)
    # no hotspot IDs on the picture: in the owner build they are shown by the debug overlay
    # (main menu → Debug → hotspot outlines), never in a normal build
    title = f"{vp_id} · {vp['panorama']} · ЗАГЛУШКА"
    draw_label(dr, (w / 2, pitch_to_y(70, h)), title, max(30, h // 28), fill=IVORY)
    return img


